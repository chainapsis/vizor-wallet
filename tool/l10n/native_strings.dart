// Builds the iOS and Android string tables from the `native*` ARB keys.
//
//   fvm dart run tool/l10n/native_strings.dart          writes the files
//   fvm dart run tool/l10n/native_strings.dart --check  fails if one is stale
//
// Notifications, background-task captions, system prompts and native error
// messages are drawn by Swift or Kotlin, outside Flutter. Their copy still
// lives in the ARB files under a `native` prefix, so translators see one
// source. This script copies those keys into ios/Runner/NativeStrings.swift
// and android/.../NativeStrings.kt. Native code picks the table that matches
// the app language Dart last sent and falls back to English.
//
// Korean comes from the translator-facing source file: the word joiners in
// lib/l10n/app_ko.arb are a Flutter line-breaking aid that native text
// rendering does not need.
import 'dart:convert';
import 'dart:io';

import 'generated_output.dart';
import 'korean_arb.dart' show wordJoiner;

const nativeKeyPrefix = 'native';

/// The ARB file each language's native strings are read from, English first.
const nativeLanguageSources = {
  'en': 'lib/l10n/app_en.arb',
  'ko': 'lib/l10n/source/app_ko.arb',
  'zh': 'lib/l10n/app_zh.arb',
};

const nativeSwiftOutputPath = 'ios/Runner/NativeStrings.swift';
const nativeKotlinOutputPath =
    'android/app/src/main/kotlin/com/keplr/vizor/NativeStrings.kt';

const _header =
    'Generated by tool/l10n/native_strings.dart from the `native*` keys in '
    'lib/l10n.\n'
    'Do not edit. Change the ARB files, then run\n'
    '`fvm dart run tool/l10n/native_strings.dart`.';

final _keyPattern = RegExp('^$nativeKeyPrefix[A-Z][A-Za-z0-9]*\$');
final _placeholderPattern = RegExp(r'\{(\w+)\}');

/// The `native*` messages of every language, keyed by language tag.
class NativeStringTable {
  NativeStringTable(this.keys, this.messages);

  /// Sorted message keys; every one has an English message.
  final List<String> keys;

  /// Language tag → key → message. Translations may be incomplete.
  final Map<String, Map<String, String>> messages;
}

/// Reads the `native*` keys from ARB file contents keyed by language tag.
///
/// Throws a [FormatException] for a message native code cannot render: ICU
/// plurals and selects, or a placeholder the English template does not
/// declare.
NativeStringTable parseNativeStrings(Map<String, String> arbJsonByTag) {
  final arbs = {
    for (final MapEntry(:key, :value) in arbJsonByTag.entries)
      key: (jsonDecode(value) as Map).cast<String, Object?>(),
  };
  final template = arbs['en']!;
  final keys = [
    for (final key in template.keys)
      if (_keyPattern.hasMatch(key)) key,
  ]..sort();
  final messages = <String, Map<String, String>>{};
  for (final MapEntry(key: tag, value: arb) in arbs.entries) {
    final table = messages[tag] = {};
    for (final key in keys) {
      final message = arb[key];
      if (message == null) continue;
      if (message is! String) {
        throw FormatException('$tag $key is not a string.');
      }
      final text = message.replaceAll(wordJoiner, '');
      _checkPlaceholders(tag, key, text, _declaredPlaceholders(template, key));
      table[key] = text;
    }
  }
  return NativeStringTable(keys, messages);
}

Set<String> _declaredPlaceholders(Map<String, Object?> template, String key) {
  final meta = template['@$key'];
  final placeholders = meta is Map ? meta['placeholders'] : null;
  return placeholders is Map ? placeholders.keys.cast<String>().toSet() : {};
}

void _checkPlaceholders(
  String tag,
  String key,
  String message,
  Set<String> declared,
) {
  for (final match in _placeholderPattern.allMatches(message)) {
    if (!declared.contains(match[1])) {
      throw FormatException(
        '$tag $key uses {${match[1]}}, which @$key does not declare.',
      );
    }
  }
  final rest = message.replaceAll(_placeholderPattern, '');
  if (rest.contains('{') || rest.contains('}')) {
    throw FormatException(
      '$tag $key uses ICU syntax. Native strings support plain {name} '
      'placeholders only.',
    );
  }
}

String _swiftLiteral(String text) {
  final escaped = text
      .replaceAll(r'\', r'\\')
      .replaceAll('"', r'\"')
      .replaceAll('\n', r'\n')
      .replaceAll('\r', r'\r')
      .replaceAll('\t', r'\t');
  return '"$escaped"';
}

String _kotlinLiteral(String text) {
  final escaped = text
      .replaceAll(r'\', r'\\')
      .replaceAll('"', r'\"')
      .replaceAll(r'$', r'\$')
      .replaceAll('\n', r'\n')
      .replaceAll('\r', r'\r')
      .replaceAll('\t', r'\t');
  return '"$escaped"';
}

String _comment(String prefix, String text) =>
    text.split('\n').map((line) => '$prefix $line'.trimRight()).join('\n');

String buildNativeSwift(NativeStringTable table) {
  final translations = [
    for (final tag in table.messages.keys)
      if (tag != 'en') tag,
  ];
  final out = StringBuffer()
    ..writeln(_comment('//', _header))
    ..writeln()
    ..writeln('import Foundation')
    ..writeln()
    ..writeln(
      '/// Copy iOS shows outside Flutter: notifications, background-task',
    )
    ..writeln('/// captions and native error messages that Dart displays.')
    ..writeln('enum NativeString: String, CaseIterable {');
  for (final key in table.keys) {
    out.writeln('  case $key');
  }
  out
    ..writeln('}')
    ..writeln()
    ..writeln('enum NativeStrings {')
    ..writeln(
      '  /// `UserDefaults.standard` key holding the app language tag Dart',
    )
    ..writeln('  /// last sent over `com.zcash.wallet/native_strings`.')
    ..writeln('  static let languageKey = "vizor_native_language"')
    ..writeln()
    ..writeln('  /// The app language; English until Dart sends one.')
    ..writeln('  static var language: String {')
    ..writeln('    UserDefaults.standard.string(forKey: languageKey) ?? "en"')
    ..writeln('  }')
    ..writeln()
    ..writeln('  static func setLanguage(_ tag: String) {')
    ..writeln('    UserDefaults.standard.set(tag, forKey: languageKey)')
    ..writeln('  }')
    ..writeln()
    ..writeln(
      '  /// `key` in `language` (default: the app language), or English when',
    )
    ..writeln(
      '  /// that language has no translation. `{name}` placeholders take',
    )
    ..writeln('  /// their value from `args`.')
    ..writeln('  static func text(')
    ..writeln('    _ key: NativeString,')
    ..writeln('    _ args: [String: String] = [:],')
    ..writeln('    language: String? = nil')
    ..writeln('  ) -> String {')
    ..writeln('    let template: String')
    ..writeln('    switch language ?? self.language {');
  for (final tag in translations) {
    out.writeln('    case "$tag": template = $tag[key] ?? en(key)');
  }
  out
    ..writeln('    default: template = en(key)')
    ..writeln('    }')
    ..writeln('    return args.reduce(template) { message, arg in')
    ..writeln(
      '      message.replacingOccurrences(of: "{\\(arg.key)}", with: arg.value)',
    )
    ..writeln('    }')
    ..writeln('  }')
    ..writeln()
    ..writeln('  private static func en(_ key: NativeString) -> String {')
    ..writeln('    switch key {');
  final english = table.messages['en']!;
  for (final key in table.keys) {
    out.writeln('    case .$key: return ${_swiftLiteral(english[key]!)}');
  }
  out
    ..writeln('    }')
    ..writeln('  }');
  for (final tag in translations) {
    final messages = table.messages[tag]!;
    out
      ..writeln()
      ..writeln('  private static let $tag: [NativeString: String] = [');
    for (final key in table.keys) {
      final message = messages[key];
      if (message == null) continue;
      out.writeln('    .$key: ${_swiftLiteral(message)},');
    }
    out.writeln('  ]');
  }
  out.writeln('}');
  return out.toString();
}

String buildNativeKotlin(NativeStringTable table) {
  final translations = [
    for (final tag in table.messages.keys)
      if (tag != 'en') tag,
  ];
  final out = StringBuffer()
    ..writeln(_comment('//', _header))
    ..writeln()
    ..writeln('package com.keplr.vizor')
    ..writeln()
    ..writeln('import android.content.Context')
    ..writeln()
    ..writeln('/**')
    ..writeln(
      ' * Copy Android shows outside Flutter: system prompts and native',
    )
    ..writeln(' * error messages that Dart displays.')
    ..writeln(' */')
    ..writeln('@Suppress("EnumEntryName")')
    ..writeln('enum class NativeString {');
  for (final key in table.keys) {
    out.writeln('    $key,');
  }
  out
    ..writeln('}')
    ..writeln()
    ..writeln('object NativeStrings {')
    ..writeln('    private const val PREFS_NAME = "vizor_native_strings"')
    ..writeln('    private const val LANGUAGE_KEY = "language"')
    ..writeln()
    ..writeln(
      '    /** The app language tag Dart last sent; English until it sends one. */',
    )
    ..writeln('    fun language(context: Context): String =')
    ..writeln(
      '        context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)',
    )
    ..writeln('            ?.getString(LANGUAGE_KEY, null) ?: "en"')
    ..writeln()
    ..writeln('    fun setLanguage(context: Context, tag: String) {')
    ..writeln(
      '        context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)',
    )
    ..writeln('            .edit()')
    ..writeln('            .putString(LANGUAGE_KEY, tag)')
    ..writeln('            .apply()')
    ..writeln('    }')
    ..writeln()
    ..writeln(
      '    fun text(context: Context, key: NativeString, vararg args: Pair<String, String>): String =',
    )
    ..writeln('        text(language(context), key, *args)')
    ..writeln()
    ..writeln('    /**')
    ..writeln(
      '     * [key] in [language], or English when that language has no',
    )
    ..writeln(
      '     * translation. `{name}` placeholders take their value from [args].',
    )
    ..writeln('     */')
    ..writeln(
      '    fun text(language: String, key: NativeString, vararg args: Pair<String, String>): String {',
    )
    ..writeln('        val template = when (language) {');
  for (final tag in translations) {
    out.writeln('            "$tag" -> $tag[key]');
  }
  out
    ..writeln('            else -> null')
    ..writeln('        } ?: en(key)')
    ..writeln(
      '        return args.fold(template) { message, (name, value) -> '
      'message.replace("{\$name}", value) }',
    )
    ..writeln('    }')
    ..writeln()
    ..writeln('    private fun en(key: NativeString): String = when (key) {');
  final english = table.messages['en']!;
  for (final key in table.keys) {
    out.writeln(
      '        NativeString.$key -> ${_kotlinLiteral(english[key]!)}',
    );
  }
  out.writeln('    }');
  for (final tag in translations) {
    final messages = table.messages[tag]!;
    out
      ..writeln()
      ..writeln('    private val $tag: Map<NativeString, String> = mapOf(');
    for (final key in table.keys) {
      final message = messages[key];
      if (message == null) continue;
      out.writeln('        NativeString.$key to ${_kotlinLiteral(message)},');
    }
    out.writeln('    )');
  }
  out.writeln('}');
  return out.toString();
}

/// Output path → expected contents, from the ARB files on disk.
Map<String, String> buildNativeStringFiles() {
  final table = parseNativeStrings({
    for (final MapEntry(key: tag, value: path) in nativeLanguageSources.entries)
      tag: File(path).readAsStringSync(),
  });
  return {
    nativeSwiftOutputPath: buildNativeSwift(table),
    nativeKotlinOutputPath: buildNativeKotlin(table),
  };
}

void main(List<String> args) {
  final Map<String, String> files;
  try {
    files = buildNativeStringFiles();
  } on FormatException catch (error) {
    stderr.writeln(error.message);
    exitCode = 1;
    return;
  }
  final check = args.contains('--check');
  for (final MapEntry(key: path, value: expected) in files.entries) {
    if (!checkGeneratedOutputPath(path)) continue;
    final output = File(path);
    if (!check) {
      writeGeneratedTextIfChanged(path, expected);
      continue;
    }
    if (!output.existsSync() || output.readAsStringSync() != expected) {
      stderr.writeln(
        '$path is stale. Run `fvm dart run tool/l10n/native_strings.dart`.',
      );
      exitCode = 1;
    }
  }
}
